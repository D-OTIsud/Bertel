/*
 * Build the public static guide from its canonical Markdown and the existing
 * partner-page template. No source Markdown, audits or build tool is deployed.
 * Run `node docs/thesaurus-render.js --write`, then the companion check.
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const md = require('./partenaires-render.js');

function replaceOnce(text, before, after) {
  if (!text.includes(before) || text.indexOf(before) !== text.lastIndexOf(before)) {
    throw new Error('The documentation template changed: ' + before.slice(0, 80));
  }
  return text.replace(before, after);
}

function publicBody(canonical, partnerSource) {
  const rendered = md.render(canonical);
  const ids = new Set([...rendered.html.matchAll(/\bid="([^"]+)"/g)].map((entry) => entry[1]));
  const partnerSection = md.render(partnerSource).toc.find((entry) => /^3\.5\s+Thésaurus versionné$/i.test(entry.text));
  if (!partnerSection) throw new Error('The partner thesaurus section is missing.');

  const html = rendered.html.replace(/<a href="([^"]+)"([^>]*)>(.*?)<\/a>/g, (_, href, attributes, label) => {
    if (href.startsWith('#')) {
      const fragment = decodeURIComponent(href.slice(1));
      const target = ids.has(fragment) ? fragment : md.slugify(fragment);
      if (!ids.has(target)) throw new Error('Unresolved guide anchor: ' + href);
      return '<a href="#' + target + '"' + attributes + '>' + label + '</a>';
    }
    if (/^guide-partenaires\.md#35-/.test(href)) {
      return '<a href="partenaires.html#' + partnerSection.id + '">' + label + '</a>';
    }
    if (href === 'README.md') return '<a href="index.html">' + label + '</a>';
    if (href === 'SQL_ROLLOUT_RUNBOOK.md') return '<a href="index.html#team-ops">' + label + '</a>';
    if (/^https?:\/\//i.test(href) || /^mailto:/i.test(href)) return _;
    // Keep the reference label, but do not advertise unavailable repository
    // paths or publish the technical/internal documents to make a link work.
    return label + ' <span class="muted">(référence interne au dépôt)</span>';
  });
  return { html, toc: rendered.toc };
}

function buildPage(canonical, template, partnerSource) {
  let page = template.replace(/\r\n/g, '\n');
  const body = publicBody(canonical, partnerSource);
  page = replaceOnce(page, '<title>API publique Bertel · Guide partenaires — OTI du Sud</title>', '<title>Guide métier du thésaurus Bertel — OTI du Sud</title>');
  page = replaceOnce(page, 'Guide développeur de l\'API publique Bertel (OTI du Sud) : authentification, endpoints, synchronisation, formats DATAtourisme / Apidae / Tourinsoft / schema.org.', 'Rédiger, traduire, relire et publier les concepts du thésaurus Bertel : guide métier de l’OTI du Sud.');
  page = replaceOnce(page, '<h1>API publique Bertel · Espace partenaires</h1>', '<h1>Bertel · Guide métier du thésaurus</h1>');
  page = replaceOnce(page, '<a href="openapi.html">OpenAPI</a>', '<a href="index.html">Documentation</a>');
  page = replaceOnce(page, '    .doc h3{', '    .doc [id]{scroll-margin-top:100px}\n    .doc h3{');
  page = replaceOnce(page, '  </style>', '    .doc .muted{color:var(--muted)}\n' +
    '    @media (max-width:640px){\n' +
    '      .topbar{position:static}\n' +
    '      .topbar-inner{flex-wrap:wrap}\n' +
    '      .topbar .titles{flex-basis:calc(100% - 54px)}\n' +
    '      .top-actions{margin-left:54px}\n' +
    '      .doc [id]{scroll-margin-top:20px}\n' +
    '    }\n' +
    '  </style>');
  const toc = body.toc.map((entry) => '<li><a href="#' + entry.id + '"' + (entry.level === 3 ? ' class="lvl3"' : '') + '>' + md.escapeHtml(entry.text) + '</a></li>').join('\n');
  page = replaceOnce(page, '<ul id="toc-list"></ul>', '<ul id="toc-list">\n' + toc + '\n</ul>');
  page = replaceOnce(page, '<main class="doc" id="doc" aria-live="polite">\n      <div class="state">Chargement du guide…</div>\n    </main>', '<main class="doc" id="doc">\n' + body.html + '\n    </main>');
  const footer = page.match(/  <footer class="footer">[\s\S]*?<\/footer>/);
  if (!footer) throw new Error('The documentation footer is missing.');
  page = replaceOnce(page, footer[0], '  <footer class="footer">\n    Guide généré depuis le guide métier versionné · <a href="index.html">Documentation Bertel</a> ·\n    <a href="partenaires.html">Guide partenaires de l’API</a>\n  </footer>');
  page = replaceOnce(page, '  <script src="partenaires-render.js"></script>\n', '');
  // The static body and table of contents work without JavaScript. Retain only
  // the existing theme control; no fetch, HTML injection or third-party parser.
  const loading = page.indexOf('      /* Chargement + rendu du guide');
  const closing = page.indexOf('    })();', loading);
  if (loading < 0 || closing < 0) throw new Error('The partner theme script changed.');
  page = page.slice(0, loading) + page.slice(closing);
  return '<!-- Generated by node docs/thesaurus-render.js --write; edit guide-metier-thesaurus.md, not this file. -->\n' + page;
}

function buildFromFiles(directory = __dirname) {
  const read = (name) => fs.readFileSync(path.join(directory, name), 'utf8');
  return buildPage(read('guide-metier-thesaurus.md'), read('partenaires.html'), read('guide-partenaires.md'));
}

module.exports = { buildPage, buildFromFiles, publicBody };
if (require.main === module) {
  if (process.argv[2] !== '--write' || process.argv.length !== 3) throw new Error('Usage: node docs/thesaurus-render.js --write');
  fs.writeFileSync(path.join(__dirname, 'thesaurus.html'), buildFromFiles());
  console.log('Generated docs/thesaurus.html from the canonical guide.');
}
