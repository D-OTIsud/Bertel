-- Read-only PostgreSQL 17 catalogue -> tbls v1.94.5 JSON datasource.
-- Source shape: official drivers/postgres/postgres.go + schema/schema.go.
-- Edit ONLY params for MCP pagination; concatenate tables/relations across pages.
-- Functions/enums occur only on page zero. Counts describe the entire live scope.
-- No data rows, credentials, settings changes, DDL or previous schema JSON are read.
WITH
params AS (SELECT 0::integer AS page_offset, 25::integer AS page_size),
catalog AS MATERIALIZED (
 SELECT c.oid,c.relname,c.relkind,n.nspname,n.nspname||'.'||c.relname AS qualified_name
 FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname NOT IN('pg_catalog','information_schema') AND n.nspname !~ '^pg_(toast|temp)'
   AND c.relkind IN('r','p','v','m','f')
),
selected AS MATERIALIZED (
 SELECT * FROM catalog ORDER BY oid LIMIT (SELECT page_size FROM params) OFFSET (SELECT page_offset FROM params)
),
column_rows AS MATERIALIZED (
 SELECT a.attrelid,a.attnum,jsonb_strip_nulls(jsonb_build_object(
   'name',a.attname,'type',CASE WHEN 'character varying'::regtype=ANY(ARRAY[a.atttypid,t.typelem])
      THEN replace(format_type(a.atttypid,a.atttypmod),'character varying','varchar') ELSE format_type(a.atttypid,a.atttypmod) END,
   'nullable',NOT(a.attnotnull OR t.typtype='d'AND t.typnotnull),
   'default',CASE WHEN a.attgenerated=''THEN pg_get_expr(d.adbin,d.adrelid) END,
   'extra_def',CASE WHEN a.attgenerated='s'THEN 'GENERATED ALWAYS AS '||pg_get_expr(d.adbin,d.adrelid)||' STORED'
      WHEN a.attgenerated='v'THEN 'GENERATED ALWAYS AS '||pg_get_expr(d.adbin,d.adrelid)||' VIRTUAL'
      WHEN a.attidentity='a'THEN 'GENERATED ALWAYS AS IDENTITY'WHEN a.attidentity='d'THEN 'GENERATED BY DEFAULT AS IDENTITY'END,
   'comment',NULLIF(col_description(a.attrelid,a.attnum),''))) AS item
 FROM pg_attribute a JOIN selected s ON s.oid=a.attrelid JOIN pg_type t ON t.oid=a.atttypid
 LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
 WHERE a.attnum>0 AND NOT a.attisdropped
),
constraint_rows AS MATERIALIZED (
 SELECT con.oid,con.conrelid,con.confrelid,con.contype,con.conindid,
   CASE WHEN con.contype='t'THEN(SELECT pg_get_triggerdef(tr.oid)FROM pg_trigger tr WHERE tr.tgconstraint=con.oid AND NOT tr.tgisinternal ORDER BY tr.oid LIMIT 1)
     ELSE pg_get_constraintdef(con.oid)END AS definition,
   s.qualified_name AS child_name,pn.nspname||'.'||pc.relname AS parent_name,
   COALESCE((SELECT jsonb_agg(a.attname ORDER BY key.position)FROM unnest(con.conkey)WITH ORDINALITY key(attnum,position)
      JOIN pg_attribute a ON a.attrelid=con.conrelid AND a.attnum=key.attnum),'[]'::jsonb)AS child_columns,
   COALESCE((SELECT jsonb_agg(a.attname ORDER BY key.position)FROM unnest(con.confkey)WITH ORDINALITY key(attnum,position)
      JOIN pg_attribute a ON a.attrelid=con.confrelid AND a.attnum=key.attnum),'[]'::jsonb)AS parent_columns,
   con.conname,NULLIF(obj_description(con.oid,'pg_constraint'),'')AS comment
 FROM pg_constraint con JOIN selected s ON s.oid=con.conrelid
 LEFT JOIN pg_class pc ON pc.oid=con.confrelid LEFT JOIN pg_namespace pn ON pn.oid=pc.relnamespace
),
index_rows AS MATERIALIZED (
 SELECT i.indrelid,i.indexrelid,jsonb_strip_nulls(jsonb_build_object(
   'name',ic.relname,'def',pg_get_indexdef(i.indexrelid),'table',s.qualified_name,
   'columns',COALESCE((SELECT jsonb_agg(a.attname ORDER BY a.attnum)FROM pg_attribute a WHERE a.attrelid=i.indexrelid AND a.attnum>0 AND NOT a.attisdropped),'[]'::jsonb),
   'comment',NULLIF(obj_description(i.indexrelid,'pg_class'),'')))AS item
 FROM pg_index i JOIN selected s ON s.oid=i.indrelid JOIN pg_class ic ON ic.oid=i.indexrelid
),
trigger_rows AS MATERIALIZED (
 SELECT t.tgrelid,t.oid,jsonb_strip_nulls(jsonb_build_object('name',t.tgname,'def',pg_get_triggerdef(t.oid),
   'comment',NULLIF(obj_description(t.oid,'pg_trigger'),'')))AS item
 FROM pg_trigger t JOIN selected s ON s.oid=t.tgrelid WHERE NOT t.tgisinternal
),
table_rows AS (
 SELECT s.oid,jsonb_strip_nulls(jsonb_build_object(
   'name',s.qualified_name,'type',CASE s.relkind WHEN'r'THEN'BASE TABLE'WHEN'p'THEN'BASE TABLE'WHEN'v'THEN'VIEW'WHEN'm'THEN'MATERIALIZED VIEW'WHEN'f'THEN'FOREIGN TABLE'END,
   'comment',NULLIF(obj_description(s.oid,'pg_class'),''),
   'columns',COALESCE((SELECT jsonb_agg(c.item ORDER BY c.attnum)FROM column_rows c WHERE c.attrelid=s.oid),'[]'::jsonb),
   'constraints',COALESCE((SELECT jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
      'name',c.conname,'type',CASE c.contype WHEN'p'THEN'PRIMARY KEY'WHEN'u'THEN'UNIQUE'WHEN'f'THEN'FOREIGN KEY'WHEN'c'THEN'CHECK'WHEN't'THEN'TRIGGER'ELSE c.contype::text END,
      'def',c.definition,'table',c.child_name,'referenced_table',COALESCE(c.parent_name,''),
      'columns',c.child_columns,'referenced_columns',c.parent_columns,'comment',c.comment))ORDER BY c.conindid,c.conname)
      FROM constraint_rows c WHERE c.conrelid=s.oid),'[]'::jsonb),
   'indexes',COALESCE((SELECT jsonb_agg(i.item ORDER BY i.indexrelid)FROM index_rows i WHERE i.indrelid=s.oid),'[]'::jsonb),
   'triggers',COALESCE((SELECT jsonb_agg(t.item ORDER BY t.oid)FROM trigger_rows t WHERE t.tgrelid=s.oid),'[]'::jsonb),
   'def',CASE WHEN s.relkind IN('v','m')THEN 'CREATE '||CASE s.relkind WHEN'v'THEN'VIEW'ELSE'MATERIALIZED VIEW'END||' '||s.relname||' AS ('||chr(10)||rtrim(pg_get_viewdef(s.oid),';')||chr(10)||')'END,
   'referenced_tables',CASE WHEN s.relkind IN('v','m')THEN COALESCE((
      SELECT jsonb_agg(ref.name ORDER BY ref.name)FROM(
       SELECT DISTINCT rn.nspname||'.'||rc.relname AS name FROM pg_rewrite rw JOIN pg_depend dep ON dep.classid='pg_rewrite'::regclass AND dep.objid=rw.oid AND dep.refclassid='pg_class'::regclass
       JOIN pg_class rc ON rc.oid=dep.refobjid JOIN pg_namespace rn ON rn.oid=rc.relnamespace
       WHERE rw.ev_class=s.oid AND rc.oid<>s.oid AND rc.relkind IN('r','p','v','m','f'))ref),'[]'::jsonb)END))AS item
 FROM selected s
),
function_rows AS (
 SELECT p.oid,jsonb_build_object('name',n.nspname||'.'||p.proname,'return_type',t.typname,
   'arguments',pg_get_function_arguments(p.oid),'type',CASE p.prokind WHEN'p'THEN'PROCEDURE'WHEN'f'THEN'FUNCTION'ELSE p.prokind::text END)AS item
 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace JOIN pg_type t ON t.oid=p.prorettype
 WHERE n.nspname NOT IN('pg_catalog','information_schema')AND n.nspname !~ '^pg_(toast|temp)'
),
enum_rows AS (
 SELECT n.nspname||'.'||t.typname AS name,jsonb_build_object('name',n.nspname||'.'||t.typname,
    'values',jsonb_agg(e.enumlabel ORDER BY e.enumsortorder))AS item
 FROM pg_type t JOIN pg_namespace n ON n.oid=t.typnamespace JOIN pg_enum e ON e.enumtypid=t.oid
 WHERE n.nspname NOT IN('pg_catalog','information_schema')AND n.nspname !~ '^pg_(toast|temp)'
 GROUP BY n.nspname,t.typname
)
SELECT jsonb_build_object(
 'name',current_database(),
 'tables',COALESCE((SELECT jsonb_agg(item ORDER BY oid)FROM table_rows),'[]'::jsonb),
 'relations',COALESCE((SELECT jsonb_agg(jsonb_build_object('table',child_name,'columns',child_columns,
     'parent_table',parent_name,'parent_columns',parent_columns,'def',definition)ORDER BY oid)FROM constraint_rows WHERE contype='f'),'[]'::jsonb),
 'functions',CASE WHEN(SELECT page_offset FROM params)=0 THEN COALESCE((SELECT jsonb_agg(item ORDER BY oid)FROM function_rows),'[]'::jsonb)ELSE'[]'::jsonb END,
 'enums',CASE WHEN(SELECT page_offset FROM params)=0 THEN COALESCE((SELECT jsonb_agg(item ORDER BY name)FROM enum_rows),'[]'::jsonb)ELSE'[]'::jsonb END,
 'driver',jsonb_build_object('name','postgres','database_version',version(),'meta',jsonb_build_object(
    'current_schema',current_schema(),'search_paths',current_schemas(false),'dict',jsonb_build_object('Functions','Stored procedures and functions'))),
 '_live_export',jsonb_build_object('captured_at',statement_timestamp(),'source','actual live PostgreSQL catalogue via bulk SELECT',
    'page_offset',(SELECT page_offset FROM params),'page_size',(SELECT page_size FROM params),
    'page_tables',(SELECT count(*)FROM selected),'total_tables',(SELECT count(*)FROM catalog),
    'total_columns',(SELECT count(*)FROM pg_attribute a JOIN catalog c ON c.oid=a.attrelid WHERE a.attnum>0 AND NOT a.attisdropped),
    'total_constraints',(SELECT count(*)FROM pg_constraint con JOIN catalog c ON c.oid=con.conrelid),
    'total_foreign_keys',(SELECT count(*)FROM pg_constraint con JOIN catalog c ON c.oid=con.conrelid WHERE con.contype='f'),
    'total_indexes',(SELECT count(*)FROM pg_index i JOIN catalog c ON c.oid=i.indrelid),
    'total_triggers',(SELECT count(*)FROM pg_trigger t JOIN catalog c ON c.oid=t.tgrelid WHERE NOT t.tgisinternal),
    'total_functions',(SELECT count(*)FROM function_rows),'total_enums',(SELECT count(*)FROM enum_rows),
    'schemas',(SELECT jsonb_agg(nspname ORDER BY nspname)FROM(SELECT DISTINCT nspname FROM catalog)s))
)AS schema_json;
